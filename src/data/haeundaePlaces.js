// Smart Search Function matching road name addresses and POIs
export function searchPlaces(query) {
  if (!query || !query.trim()) return [];
  
  // Normalize query: remove spaces and lowercase
  const raw = query.trim();
  const normalized = raw.toLowerCase().replace(/\s+/g, '');

  const matches = [];

  for (const place of HAEUNDAE_PLACES) {
    const nameNorm = place.name.toLowerCase().replace(/\s+/g, '');
    const addrNorm = (place.roadAddress || '').toLowerCase().replace(/\s+/g, '');
    const tagsNorm = (place.tags || []).map(t => t.toLowerCase().replace(/\s+/g, ''));

    let score = 0;

    // Exact or prefix matches get high priority
    if (nameNorm.startsWith(normalized)) score += 100;
    else if (nameNorm.includes(normalized)) score += 50;

    if (addrNorm.startsWith(normalized)) score += 80;
    else if (addrNorm.includes(normalized)) score += 40;

    for (const tag of tagsNorm) {
      if (tag === normalized) score += 90;
      else if (tag.includes(normalized)) score += 30;
    }

    if (score > 0) {
      matches.push({ ...place, score });
    }
  }

  // Sort by score descending
  matches.sort((a, b) => b.score - a.score);

  return matches.slice(0, 8);
}
